#!/usr/bin/env python3
"""AgroNova engineering sizing calculations (drive, battery, structure, stability, wiring).

Every input is an ASSUMPTION (IDs A-xx, see docs/requirements/SRS.md) unless marked as a
physical constant or a standard material property. Run:  python tools/sizing.py > docs/calculations/RESULTS.md
"""
from __future__ import annotations

import math
from dataclasses import asdict, dataclass

G = 9.81  # m/s^2, physical constant
RHO_CU = 1.68e-8  # ohm*m, copper resistivity at 20 C (physical constant)


@dataclass(frozen=True)
class Inputs:
    robot_mass_kg: float = 45.0  # A-9 estimate of empty robot incl. battery
    payload_kg: float = 20.0  # A-2
    wheel_radius_m: float = 0.15  # A-7 (300 mm dia. pneumatic/solid wheel for tilled soil)
    n_wheels: int = 4  # A-1 skid-steer
    track_width_m: float = 0.50  # A-7 fits 90 cm cotton inter-row with margin
    wheelbase_m: float = 0.50  # A-7
    cog_height_m: float = 0.40  # A-10 estimated, verify by measurement (TC-MECH-004)
    v_max_mps: float = 1.0  # A-3
    accel_mps2: float = 0.5  # A-11
    slope_deg: float = 10.0  # A-4
    crr: float = 0.10  # A-12 rolling-resistance coeff. for loose/tilled soil (assumed, measure)
    skid_turn_factor: float = 1.5  # A-13 extra torque demand during skid-steer turning (assumed)
    design_factor: float = 1.5  # A-14 margin applied to torque
    drivetrain_eff: float = 0.75  # A-15 gearbox + chain/coupling efficiency (assumed)
    bus_voltage_v: float = 25.6  # A-5 8S LiFePO4 nominal (8 x 3.2 V)
    runtime_h: float = 4.0  # A-16 one field session
    duty_avg_power_frac: float = 0.35  # A-17 average traction power / peak traction power
    aux_power_w: float = 30.0  # A-18 Pi 5 + sensors + ESP32 + drivers idle (estimate)
    usable_dod: float = 0.80  # A-19 LiFePO4 usable depth of discharge
    # Structure: mild-steel square tube IS 2062 E250 (yield 250 MPa standard min.)
    tube_outer_m: float = 0.025
    tube_wall_m: float = 0.0015
    yield_mpa: float = 250.0
    e_gpa: float = 200.0
    beam_span_m: float = 0.50
    cable_len_m: float = 1.5  # one-way battery -> driver run (A-20)


def total_mass(i: Inputs) -> float:
    return i.robot_mass_kg + i.payload_kg


def traction_force_n(i: Inputs) -> float:
    m = total_mass(i)
    th = math.radians(i.slope_deg)
    return m * G * (i.crr * math.cos(th) + math.sin(th)) + m * i.accel_mps2


def wheel_torque_nm(i: Inputs) -> float:
    """Required continuous design torque per wheel, incl. turning and design factor."""
    return traction_force_n(i) * i.wheel_radius_m / i.n_wheels * i.skid_turn_factor * i.design_factor


def wheel_rpm(i: Inputs) -> float:
    return i.v_max_mps / i.wheel_radius_m * 60 / (2 * math.pi)


def peak_traction_power_w(i: Inputs) -> float:
    return traction_force_n(i) * i.v_max_mps / i.drivetrain_eff


def battery(i: Inputs) -> dict:
    avg_w = peak_traction_power_w(i) * i.duty_avg_power_frac + i.aux_power_w
    wh_needed = avg_w * i.runtime_h / i.usable_dod
    ah = wh_needed / i.bus_voltage_v
    peak_a = (peak_traction_power_w(i) * i.skid_turn_factor + i.aux_power_w) / i.bus_voltage_v
    return {"avg_power_w": avg_w, "energy_wh": wh_needed, "capacity_ah": ah, "peak_current_a": peak_a}


def tube_section(i: Inputs) -> tuple[float, float]:
    """Second moment of area I [m^4] and section modulus Z [m^3] of a square tube."""
    o, w = i.tube_outer_m, i.tube_wall_m
    inner = o - 2 * w
    second_moment = (o**4 - inner**4) / 12
    return second_moment, second_moment / (o / 2)


def frame_beam(i: Inputs, dynamic_factor: float = 2.0) -> dict:
    """Simply supported side rail, half the total weight x dynamic factor (A-21) as central point load."""
    p = total_mass(i) * G / 2 * dynamic_factor
    second_moment, z = tube_section(i)
    m_max = p * i.beam_span_m / 4
    stress = m_max / z / 1e6
    defl = p * i.beam_span_m**3 / (48 * i.e_gpa * 1e9 * second_moment)
    return {"load_n": p, "moment_nm": m_max, "stress_mpa": stress, "fos": i.yield_mpa / stress,
            "deflection_mm": defl * 1e3}


def tipping(i: Inputs) -> dict:
    lateral = math.degrees(math.atan((i.track_width_m / 2) / i.cog_height_m))
    longitudinal = math.degrees(math.atan((i.wheelbase_m / 2) / i.cog_height_m))
    return {"lateral_tip_deg": lateral, "longitudinal_tip_deg": longitudinal,
            "lateral_margin_vs_slope": lateral / i.slope_deg}


def wire(i: Inputs, area_mm2: float, current_a: float) -> dict:
    r = RHO_CU * (2 * i.cable_len_m) / (area_mm2 * 1e-6)
    drop = current_a * r
    return {"area_mm2": area_mm2, "drop_v": drop, "drop_pct": 100 * drop / i.bus_voltage_v,
            "loss_w": current_a**2 * r}


def report(i: Inputs | None = None) -> str:
    i = i or Inputs()
    b = battery(i)
    fb = frame_beam(i)
    tp = tipping(i)
    lines = ["# AgroNova sizing results (generated by tools/sizing.py)", "",
             "All values are calculated from the ASSUMED inputs below; none are measured.", "",
             "## Inputs", "| Input | Value |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in asdict(i).items()]
    lines += ["", "## Drive", "| Quantity | Value |", "|---|---|",
              f"| Gross mass | {total_mass(i):.1f} kg |",
              f"| Traction force (slope+rolling+accel) | {traction_force_n(i):.1f} N |",
              f"| Design torque per wheel | {wheel_torque_nm(i):.1f} N·m |",
              f"| Wheel speed at v_max | {wheel_rpm(i):.1f} rpm |",
              f"| Peak traction power (all wheels, at motors) | {peak_traction_power_w(i):.0f} W |",
              f"| Per-motor peak mechanical power | {peak_traction_power_w(i) / i.n_wheels:.0f} W |",
              "", "## Battery", "| Quantity | Value |", "|---|---|",
              f"| Average power | {b['avg_power_w']:.0f} W |",
              f"| Energy required (incl. DoD) | {b['energy_wh']:.0f} Wh |",
              f"| Capacity at {i.bus_voltage_v} V | {b['capacity_ah']:.1f} Ah |",
              f"| Estimated peak current | {b['peak_current_a']:.1f} A |",
              f"| Main fuse (1.25 x peak, round up to std) | >= {1.25 * b['peak_current_a']:.0f} A |",
              "", "## Frame side rail (25x25x1.5 mild-steel tube, E250)", "| Quantity | Value |",
              "|---|---|",
              f"| Point load (x2 dynamic) | {fb['load_n']:.0f} N |",
              f"| Bending stress | {fb['stress_mpa']:.1f} MPa |",
              f"| Factor of safety vs yield | {fb['fos']:.2f} |",
              f"| Mid-span deflection | {fb['deflection_mm']:.2f} mm |",
              "", "## Static stability", "| Quantity | Value |", "|---|---|",
              f"| Lateral tip-over angle | {tp['lateral_tip_deg']:.1f}° |",
              f"| Longitudinal tip-over angle | {tp['longitudinal_tip_deg']:.1f}° |",
              f"| Lateral margin vs {i.slope_deg}° design slope | {tp['lateral_margin_vs_slope']:.2f}x |",
              "", "## Main power cable voltage drop (round trip, 20 °C copper)",
              "| Area | Drop | Drop % | Loss |", "|---|---|---|---|"]
    for a in (2.5, 4.0, 6.0, 10.0):
        w = wire(i, a, b["peak_current_a"])
        lines.append(f"| {a} mm² | {w['drop_v']:.2f} V | {w['drop_pct']:.1f} % | {w['loss_w']:.1f} W |")
    lines += ["", "Ampacity must be checked against the chosen cable manufacturer's datasheet (TBD)."]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(report(), end="")
